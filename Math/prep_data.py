CODE={'text':'t','inline':'i','display':'d','table':'b'}
SPACE=re.compile(r'[ \t　]{2,}')
# 清洗源 PDF 夹带的推广水印与外链（全库扫描仅 2 处，同一域名）
URL=re.compile(r'https?://[^\s）)】"》]+')
WATERMARK=re.compile(r'[，,。.\s]*这是一条.*$')
TAIL=re.compile(r'[（(]\s*这里\s*[）)]?\s*$')

def norm(s):
    s=s.replace('\r','')
    s=URL.sub('',s)
    s=WATERMARK.sub('',s)
    s=TAIL.sub('',s)
    s=SPACE.sub(' ',s)
    return s.strip()

qs=json.load(open('questions.json'))
out=[]
tag_stat={}; matched=0
for q in qs:
    hay=' '.join(str(v) for k,v in q['segs']).lower()
    tags=[]
    for tname,kws in TAG_MAP.get(q['chapterNo'],[]):
        if any(kw.lower() in hay for kw in kws):
            tags.append(tname)
    if not tags:
        tags=['本章综合']  # 兜底
    else:
        matched+=1
    for t in tags: tag_stat[t]=tag_stat.get(t,0)+1
    segs=[]
    for k,v in q['segs']:
        vv = norm(v) if k=='text' else URL.sub('', str(v)).strip()
        if k=='text' and vv=='' : 
            # 保留换行标记
            if '\n' in v: segs.append(['t','\n'])
            continue
        segs.append([CODE.get(k,'t'), vv])
    out.append({
        'id': len(out),
        's': q['subject'], 'c': q['chapterNo'], 'cn': q['chapter'],
        'lv': q['tier'], 'tp': q['qtype'], 'n': q['localNo'], 'pg': q['page'],
        'tg': tags, 'seg': segs,
    })
json.dump(out, open('embedded_data.json','w'), ensure_ascii=False, separators=(',',':'))
print('questions:',len(out),'tag-keyword matched: %d (%.1f%%)'%(matched,100*matched/len(out)))
print('distinct tags:',len(tag_stat))
for t,c in sorted(tag_stat.items(), key=lambda x:-x[1]):
    print('  %3d  %s'%(c,t))
